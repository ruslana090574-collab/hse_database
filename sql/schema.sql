-- Firebird 3.0+, script for isql. UNO uses the statement boundaries in schema.json.
CREATE TABLE "Gender" ("GenderCode" CHAR(1) NOT NULL PRIMARY KEY CHECK ("GenderCode" IN ('1','2')),
"GenderName" VARCHAR(7) NOT NULL UNIQUE,
"GenderSymbol" CHAR(1) NOT NULL UNIQUE,
CHECK (("GenderCode"='1' AND "GenderName"='мужской' AND "GenderSymbol"='M') OR
       ("GenderCode"='2' AND "GenderName"='женский' AND "GenderSymbol"='F')));

CREATE TABLE "Currency" ("CurrencyCode" CHAR(3) NOT NULL PRIMARY KEY CHECK ("CurrencyCode" SIMILAR TO '[0-9]{3}'),
"AlphaCode" CHAR(3) NOT NULL UNIQUE CHECK ("AlphaCode" SIMILAR TO '[A-Z]{3}'),
"CurrencyName" VARCHAR(50) NOT NULL UNIQUE CHECK (CHAR_LENGTH(TRIM("CurrencyName"))>0));

CREATE TABLE "ExchangeRate" ("CurrencyCode" CHAR(3) NOT NULL,
"RateDate" DATE NOT NULL CHECK ("RateDate"<=CURRENT_DATE),
"Rate" DECIMAL(12,2) NOT NULL CHECK ("Rate">0),
PRIMARY KEY ("CurrencyCode","RateDate"),
FOREIGN KEY ("CurrencyCode") REFERENCES "Currency" ("CurrencyCode") ON UPDATE CASCADE);

CREATE TABLE "Country" ("CountryCode" CHAR(3) NOT NULL PRIMARY KEY CHECK ("CountryCode" SIMILAR TO '[0-9]{3}'),
"CountryName" VARCHAR(100) NOT NULL UNIQUE CHECK (CHAR_LENGTH(TRIM("CountryName"))>0),
"CurrencyCode" CHAR(3) NOT NULL,
"Coverage" INTEGER NOT NULL CHECK ("Coverage">0),
"Factor" DECIMAL(5,2) NOT NULL CHECK ("Factor">0),
FOREIGN KEY ("CurrencyCode") REFERENCES "Currency" ("CurrencyCode") ON UPDATE CASCADE);

CREATE TABLE "ServiceCategory" ("CategoryCode" CHAR(2) NOT NULL PRIMARY KEY CHECK ("CategoryCode" SIMILAR TO '[0-9]{2}'),
"CategoryName" VARCHAR(30) NOT NULL UNIQUE CHECK (CHAR_LENGTH(TRIM("CategoryName"))>0));

CREATE TABLE "Service" ("ServiceCode" CHAR(3) NOT NULL PRIMARY KEY CHECK ("ServiceCode" SIMILAR TO '[0-9]{3}'),
"CategoryCode" CHAR(2) NOT NULL,
"ServiceName" VARCHAR(50) NOT NULL CHECK (CHAR_LENGTH(TRIM("ServiceName"))>0),
FOREIGN KEY ("CategoryCode") REFERENCES "ServiceCategory" ("CategoryCode") ON UPDATE CASCADE);

CREATE TABLE "ServicePrice" ("ServiceCode" CHAR(3) NOT NULL,
"PriceDate" DATE NOT NULL CHECK ("PriceDate"<=CURRENT_DATE),
"BasePrice" DECIMAL(12,2) NOT NULL CHECK ("BasePrice">0),
PRIMARY KEY ("ServiceCode","PriceDate"),
FOREIGN KEY ("ServiceCode") REFERENCES "Service" ("ServiceCode") ON UPDATE CASCADE);

CREATE TABLE "Client" ("PassportNo" CHAR(9) NOT NULL PRIMARY KEY CHECK ("PassportNo" SIMILAR TO '[0-9]{9}'),
"FullName" VARCHAR(40) NOT NULL CHECK (REPLACE("FullName",'-',' ') SIMILAR TO '[A-Za-z ]+' AND CHAR_LENGTH(TRIM(REPLACE("FullName",'-',' ')))>0),
"BirthDate" DATE NOT NULL CHECK (DATEADD(18 YEAR TO "BirthDate")<=CURRENT_DATE),
"GenderCode" CHAR(1) NOT NULL,
"IssueDate" DATE NOT NULL CHECK ("IssueDate"<=CURRENT_DATE),
"ExpiryDate" DATE NOT NULL CHECK ("ExpiryDate">CURRENT_DATE),
CHECK ("IssueDate">"BirthDate" AND "ExpiryDate">"IssueDate"),
FOREIGN KEY ("GenderCode") REFERENCES "Gender" ("GenderCode") ON UPDATE CASCADE);

CREATE TABLE "Agent" ("AgentID" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
"AgentName" VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM("AgentName"))>0),
"AgentPassport" CHAR(10) NOT NULL UNIQUE CHECK ("AgentPassport" SIMILAR TO '[0-9]{10}'),
"IssueDate" DATE NOT NULL CHECK ("IssueDate"<=CURRENT_DATE),
"Issuer" VARCHAR(200) NOT NULL,
"IsActive" SMALLINT DEFAULT 1 NOT NULL CHECK ("IsActive" IN (0,1)));

CREATE TABLE "AgentContract" ("ContractNo" VARCHAR(20) NOT NULL PRIMARY KEY,
"AgentID" INTEGER NOT NULL,
"ContractDate" DATE DEFAULT CURRENT_DATE NOT NULL,
"ContractStart" DATE NOT NULL,
"ContractEnd" DATE NOT NULL,
"CommissionPct" DECIMAL(5,2) NOT NULL CHECK ("CommissionPct">=0 AND "CommissionPct"<=100),
"BankBIK" CHAR(9) NOT NULL CHECK ("BankBIK" SIMILAR TO '[0-9]{9}'),
"BankAccount" CHAR(20) NOT NULL CHECK ("BankAccount" SIMILAR TO '[0-9]{20}'),
"BankName" VARCHAR(100) NOT NULL,
CHECK ("ContractStart">="ContractDate" AND "ContractEnd">="ContractStart"),
FOREIGN KEY ("AgentID") REFERENCES "Agent" ("AgentID"));

CREATE TABLE "Policy" ("PolicyID" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
"PassportNo" CHAR(9) NOT NULL,
"IssuedOn" DATE DEFAULT CURRENT_DATE NOT NULL CHECK ("IssuedOn"<=CURRENT_DATE),
"StartsOn" DATE NOT NULL,
"EndsOn" DATE NOT NULL,
"CountryCode" CHAR(3) NOT NULL,
"ContractNo" VARCHAR(20) NOT NULL,
"PolicyFactor" DECIMAL(5,2) NOT NULL CHECK ("PolicyFactor">0),
"PolicyCoverage" INTEGER NOT NULL CHECK ("PolicyCoverage">0),
"PolicyCurrency" CHAR(3) NOT NULL,
"PolicyRate" DECIMAL(12,2) NOT NULL CHECK ("PolicyRate">0),
"RateDate" DATE NOT NULL,
CHECK ("StartsOn">="IssuedOn"),
CHECK ("EndsOn">=DATEADD(7 DAY TO "StartsOn")),
FOREIGN KEY ("PassportNo") REFERENCES "Client" ("PassportNo") ON UPDATE CASCADE,
FOREIGN KEY ("CountryCode") REFERENCES "Country" ("CountryCode") ON UPDATE CASCADE,
FOREIGN KEY ("ContractNo") REFERENCES "AgentContract" ("ContractNo"),
FOREIGN KEY ("PolicyCurrency","RateDate") REFERENCES "ExchangeRate" ("CurrencyCode","RateDate"));

CREATE TABLE "PolicyService" ("PolicyID" INTEGER NOT NULL,
"ServiceCode" CHAR(3) NOT NULL,
"TariffDate" DATE NOT NULL,
"AgreedPrice" DECIMAL(12,2) NOT NULL CHECK ("AgreedPrice">0),
PRIMARY KEY ("PolicyID","ServiceCode"),
FOREIGN KEY ("PolicyID") REFERENCES "Policy" ("PolicyID") ON DELETE CASCADE,
FOREIGN KEY ("ServiceCode","TariffDate") REFERENCES "ServicePrice" ("ServiceCode","PriceDate") ON UPDATE CASCADE);

CREATE EXCEPTION E_AGE 'На дату оформления клиенту должно быть 18 лет';

CREATE EXCEPTION E_PASSPORT 'Паспорт должен действовать весь срок поездки';

CREATE EXCEPTION E_CONTRACT 'Дата оформления вне срока договора агента';

CREATE EXCEPTION E_RATE 'Нет курса на дату оформления';

CREATE EXCEPTION E_PRICE 'Нет тарифа услуги на дату оформления';

CREATE EXCEPTION E_HISTORY 'Дата оформления и страна полиса с услугами неизменяемы';

