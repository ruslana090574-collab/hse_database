CREATE TRIGGER BIU_POLICY FOR "Policy" ACTIVE BEFORE INSERT OR UPDATE POSITION 0 AS
DECLARE VARIABLE DOB DATE; DECLARE VARIABLE ISSUED DATE; DECLARE VARIABLE EXPIRY DATE;
DECLARE VARIABLE D1 DATE; DECLARE VARIABLE D2 DATE;
BEGIN
 SELECT "BirthDate","IssueDate","ExpiryDate" FROM "Client" WHERE "PassportNo"=NEW."PassportNo" INTO :DOB,:ISSUED,:EXPIRY;
 IF (DATEADD(18 YEAR TO :DOB)>NEW."IssuedOn") THEN EXCEPTION E_AGE;
 IF (:ISSUED>NEW."IssuedOn" OR :EXPIRY<NEW."EndsOn") THEN EXCEPTION E_PASSPORT;
 SELECT "ContractStart","ContractEnd" FROM "AgentContract" WHERE "ContractNo"=NEW."ContractNo" INTO :D1,:D2;
 IF (NEW."IssuedOn"<:D1 OR NEW."IssuedOn">:D2) THEN EXCEPTION E_CONTRACT;
 IF (UPDATING AND (NEW."IssuedOn"<>OLD."IssuedOn" OR NEW."CountryCode"<>OLD."CountryCode")) THEN
  IF (EXISTS(SELECT 1 FROM "PolicyService" WHERE "PolicyID"=OLD."PolicyID")) THEN EXCEPTION E_HISTORY;
 IF (INSERTING OR NEW."IssuedOn"<>OLD."IssuedOn" OR NEW."CountryCode"<>OLD."CountryCode") THEN BEGIN
  SELECT "Factor","Coverage","CurrencyCode" FROM "Country" WHERE "CountryCode"=NEW."CountryCode" INTO NEW."PolicyFactor",NEW."PolicyCoverage",NEW."PolicyCurrency";
  SELECT MAX("RateDate") FROM "ExchangeRate" WHERE "CurrencyCode"=NEW."PolicyCurrency" AND "RateDate"<=NEW."IssuedOn" INTO NEW."RateDate";
  IF (NEW."RateDate" IS NULL) THEN EXCEPTION E_RATE;
  SELECT "Rate" FROM "ExchangeRate" WHERE "CurrencyCode"=NEW."PolicyCurrency" AND "RateDate"=NEW."RateDate" INTO NEW."PolicyRate";
 END
END^
SET TERM ; ^

