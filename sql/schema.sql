CREATE TRIGGER BIU_SERVICE FOR "PolicyService" ACTIVE BEFORE INSERT OR UPDATE POSITION 0 AS
DECLARE VARIABLE ISSUED DATE;
BEGIN
 IF (INSERTING OR NEW."ServiceCode"<>OLD."ServiceCode" OR NEW."PolicyID"<>OLD."PolicyID") THEN BEGIN
  SELECT "IssuedOn" FROM "Policy" WHERE "PolicyID"=NEW."PolicyID" INTO :ISSUED;
  SELECT MAX("PriceDate") FROM "ServicePrice" WHERE "ServiceCode"=NEW."ServiceCode" AND "PriceDate"<=:ISSUED INTO NEW."TariffDate";
  IF (NEW."TariffDate" IS NULL) THEN EXCEPTION E_PRICE;
  SELECT "BasePrice" FROM "ServicePrice" WHERE "ServiceCode"=NEW."ServiceCode" AND "PriceDate"=NEW."TariffDate" INTO NEW."AgreedPrice";
 END
END^
SET TERM ; ^

CREATE VIEW "PolicySummary" AS SELECT p."PolicyID",p."IssuedOn",p."StartsOn",p."EndsOn",c."PassportNo",c."FullName",c."BirthDate",g."GenderSymbol" AS "Gender",s."CountryName",p."PolicyCoverage",v."AlphaCode" AS "CurrencyLabel",p."PolicyFactor",p."PolicyRate",p."RateDate",
DATEDIFF(DAY FROM p."StartsOn" TO p."EndsOn") AS "Days",
CAST(COALESCE((SELECT SUM(j."AgreedPrice") FROM "PolicyService" j WHERE j."PolicyID"=p."PolicyID"),0) AS DECIMAL(12,2)) AS "DailyServicesRUB",
CAST(ROUND(COALESCE((SELECT SUM(j."AgreedPrice") FROM "PolicyService" j WHERE j."PolicyID"=p."PolicyID"),0)*p."PolicyFactor"*DATEDIFF(DAY FROM p."StartsOn" TO p."EndsOn"),2) AS DECIMAL(14,2)) AS "PremiumRUB",
CAST(p."PolicyCoverage"*p."PolicyRate" AS DECIMAL(16,2)) AS "CoverageRUB",
a."AgentID",a."AgentName",d."ContractNo",d."CommissionPct"
FROM "Policy" p JOIN "Client" c ON c."PassportNo"=p."PassportNo"
JOIN "Gender" g ON g."GenderCode"=c."GenderCode"
JOIN "Country" s ON s."CountryCode"=p."CountryCode"
JOIN "Currency" v ON v."CurrencyCode"=p."PolicyCurrency"
JOIN "AgentContract" d ON d."ContractNo"=p."ContractNo"
JOIN "Agent" a ON a."AgentID"=d."AgentID";

